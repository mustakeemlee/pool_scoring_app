// scripts/generate-selfhost-secrets.mjs
//
// Generates dev-grade secrets for the self-hosted docker-compose stack
// (Sub-phase A) and writes them to .env.selfhost (gitignored). Refuses to
// overwrite an existing file, since regenerating would invalidate any
// already-issued GoTrue sessions and the anon/service keys baked into an
// already-built frontend image.
import { randomBytes, createHmac } from 'node:crypto';
import { writeFileSync, existsSync } from 'node:fs';

const outputPath = '.env.selfhost';
if (existsSync(outputPath)) {
  console.error(`${outputPath} already exists -- refusing to overwrite. Delete it first if you want to regenerate.`);
  process.exit(1);
}

function base64url(buf) {
  return buf.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function signJwt(payload, secret) {
  const header = { alg: 'HS256', typ: 'JWT' };
  const encodedHeader = base64url(Buffer.from(JSON.stringify(header)));
  const encodedPayload = base64url(Buffer.from(JSON.stringify(payload)));
  const data = `${encodedHeader}.${encodedPayload}`;
  const signature = base64url(createHmac('sha256', secret).update(data).digest());
  return `${data}.${signature}`;
}

const jwtSecret = randomBytes(32).toString('base64');
// base64url, not base64: this value is embedded directly in a postgresql://
// connection URL (GOTRUE_DB_DATABASE_URL, PGRST_DB_URI) -- a raw base64
// password can contain '/', which breaks URL parsing.
const postgresPassword = base64url(randomBytes(24));
// Per-role passwords so the most-exposed database roles don't share the
// superuser's credentials: AUTH_DB_PASSWORD -> supabase_auth_admin (GoTrue),
// AUTHENTICATOR_DB_PASSWORD -> authenticator (PostgREST). base64url for the
// same URL-safety reason as POSTGRES_PASSWORD above.
const authDbPassword = base64url(randomBytes(24));
const authenticatorDbPassword = base64url(randomBytes(24));
const nowSeconds = Math.floor(Date.now() / 1000);
const expSeconds = nowSeconds + 10 * 365 * 24 * 3600; // 10 years -- dev-grade, rotate before real hosting

const anonKey = signJwt({ role: 'anon', iss: 'pool-league-selfhost', iat: nowSeconds, exp: expSeconds }, jwtSecret);
const serviceRoleKey = signJwt(
  { role: 'service_role', iss: 'pool-league-selfhost', iat: nowSeconds, exp: expSeconds },
  jwtSecret,
);

const content = `# Generated by scripts/generate-selfhost-secrets.mjs -- dev-grade values.
# Rotate ALL of these before ever pointing this stack at a real, internet-facing host.
JWT_SECRET=${jwtSecret}
POSTGRES_PASSWORD=${postgresPassword}
AUTH_DB_PASSWORD=${authDbPassword}
AUTHENTICATOR_DB_PASSWORD=${authenticatorDbPassword}
ANON_KEY=${anonKey}
SERVICE_ROLE_KEY=${serviceRoleKey}
`;

writeFileSync(outputPath, content);
console.log(`Wrote ${outputPath}`);
